// Generates SQL only. Never connects to a database. The directory contains no people.
import { readFileSync, writeFileSync } from 'node:fs';
const directory = JSON.parse(readFileSync(new URL('./data/wsmc-directory-2026.json', import.meta.url)));
const q = (v) => v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;
const insert = (table, row) => `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(q).join(', ')});`;
// Directory-only output is additive and excludes every fictional/demo record.
if (process.argv[2] === '--directory') {
 const output = process.argv[3];
 if (!output) throw new Error('Usage: node scripts/generate-showcase.mjs --directory OUTPUT.sql');
 const rows = ['-- Additive 2026 directory bootstrap. Review name/ID matches before production use.', 'PRAGMA foreign_keys = ON;',
  "INSERT INTO seasons (id, year, name, status) SELECT 'season-2026', 2026, '2026 WSMC', 'active' WHERE NOT EXISTS (SELECT 1 FROM seasons WHERE year = 2026);"];
 for (const { number, name } of directory.regions) {
  const id = number === 11 ? 'region-virtual-2026' : `region-${number}-2026`;
  rows.push(`INSERT INTO regions (id, season_id, number, name) SELECT ${q(id)}, (SELECT id FROM seasons WHERE year = 2026), ${number}, ${q(name)} WHERE NOT EXISTS (SELECT 1 FROM regions r JOIN seasons s ON s.id = r.season_id WHERE s.year = 2026 AND r.number = ${number});`);
 }
 for (const { id, name, division } of directory.schools) {
  rows.push(`INSERT INTO schools (id, name, short_name, division) SELECT ${q(id)}, ${q(name)}, ${q(name)}, ${division} WHERE NOT EXISTS (SELECT 1 FROM schools WHERE id = ${q(id)} OR lower(trim(name)) = lower(${q(name)}) OR lower(trim(short_name)) = lower(${q(name)}));`);
 }
 writeFileSync(output, rows.join('\n') + '\n');
 console.log(`Generated directory only: ${output}`);
 process.exit(0);
}
const sql = ['-- Generated by scripts/generate-showcase.mjs; local showcase ONLY.', '-- Real directory; fictional students, staff, scores and demonstration dates.', 'PRAGMA foreign_keys = ON;', readFileSync(new URL('./reset-v2.sql', import.meta.url), 'utf8')];
const add = (table, row) => sql.push(insert(table, row));
const season = 'season-2026';
add('seasons', { id: season, year: 2026, name: '2026 WSMC', status: 'active' });
add('users', { id: 'user-coordinator', email: 'coordinator@wsmc.example', display_name: 'Morgan Ellis (Demo)', status: 'active' });
add('statewide_assignments', { id: 'assignment-system', user_id: 'user-coordinator', season_id: null });
add('statewide_assignments', { id: 'assignment-state-2026', user_id: 'user-coordinator', season_id: season });
const stages = ['finalized', 'registration_open', 'roster_locked', 'setup', 'scoring', 'registration_open', 'finalized', 'scoring', 'registration_open', 'setup', 'registration_open'];
const contestId = (n) => n === 11 ? 'contest-virtual-2026' : `contest-region-${n}`;
const regionId = (n) => n === 11 ? 'region-virtual-2026' : `region-${n}-2026`;
for (const { number, name } of directory.regions) {
 add('regions', { id: regionId(number), season_id: season, number, name });
 add('contests', { id: contestId(number), season_id: season, region_id: regionId(number), kind: 'regional', name: `${number === 11 ? 'Virtual' : `Region ${number} — ${name}`} Regional Contest`, starts_at: Date.parse('2026-03-11T09:00:00-07:00'), lifecycle: stages[number - 1], results_published_at: number === 1 ? Date.parse('2026-03-12T12:00:00-07:00') : null, settings_json: '{}' });
 add('users', { id: `user-regional-${number}`, email: `regional${number}@wsmc.example`, display_name: `${name} Coordinator (Demo)`, status: 'active' });
 add('regional_coordinator_assignments', { user_id: `user-regional-${number}`, contest_id: contestId(number) });
}
add('contests', { id: 'contest-state-2026', season_id: season, region_id: null, kind: 'state', name: '2026 State Contest', starts_at: Date.parse('2026-04-18T09:30:00-07:00'), lifecycle: 'setup', settings_json: '{"topicalIndividualAllowed":true,"crossSchoolTopicalTeamsAllowed":false}' });
const firstNames = ['Avery', 'Jordan', 'Riley', 'Casey', 'Taylor', 'Quinn', 'Cameron', 'Sage'];
const lastNames = ['Bennett', 'Chen', 'Diaz', 'Evans', 'Flores', 'Gupta', 'Harris', 'Ito', 'Jones', 'Kim', 'Lopez', 'Martin', 'Nguyen', 'Ortiz', 'Patel', 'Reed', 'Singh', 'Turner', 'Walker'];
const knowdownCounts = new Map();
for (const [index, school] of directory.schools.entries()) {
 const { id, name, division, region } = school;
 const cid = contestId(region), stage = stages[region - 1], slug = id.slice(7);
 add('schools', { id, name, short_name: name, division });
 const uid = `user-coach-${slug}`, pid = `participation-${region}-${slug}`;
 add('users', { id: uid, email: `coach.${slug}@wsmc.example`, display_name: `${name} Coach (Demo)`, status: 'active' });
 add('coach_assignments', { user_id: uid, season_id: season, school_id: id });
 add('school_participations', { id: pid, contest_id: cid, school_id: id, division, invitation_status: stage === 'setup' ? 'invited' : 'accepted' });
 const students = [];
 for (let j = 0; j < 8; j++) {
  const sid = `student-${slug}-${j + 1}`, grade = 9 + j % 4;
  students.push({ id: sid, grade });
  add('annual_students', { id: sid, season_id: season, school_id: id, name: `${firstNames[j]} ${lastNames[(index + j * 3) % lastNames.length]}`, actual_grade: grade });
  if (stage !== 'setup') add('contest_roster_members', { contest_id: cid, participation_id: pid, annual_student_id: sid });
 }
 if (stage === 'setup') continue;
 const definitions = [
  ['project', students.slice(0, 3)], ['team_contest', students.slice(0, 3)], ['topical_team', students.slice(0, 3)],
  ...students.slice(3).map(s => ['topical_individual', [s]]), ...students.map(s => ['knowdown', [s]])
 ];
 const counts = new Map();
 for (const [category, members] of definitions) {
  const number = (counts.get(category) ?? 0) + 1; counts.set(category, number);
  const eid = `entry-${region}-${slug}-${category}-${number}`;
  const team = ['project', 'team_contest', 'topical_team'].includes(category);
  add('entries', { id: eid, contest_id: cid, owner_school_id: id, category, entry_kind: team ? 'team' : 'individual', entry_number: number, division });
  for (const s of members) add('entry_members', { entry_id: eid, annual_student_id: s.id, competing_grade: team ? s.grade : null });
  if (!['scoring', 'finalized'].includes(stage)) continue;
  // Scoring regions deliberately contain missing results and one-part topical scores.
  if (stage === 'scoring' && number % 3 === 0) continue;
  const result = { entry_id: eid, score: null, part1: null, part2: null, placement: null, knowdown_outcome: null, version: 1, last_edited_by: `user-regional-${region}` };
  if (category === 'knowdown') {
   const rank = (knowdownCounts.get(region) ?? 0) + 1; knowdownCounts.set(region, rank);
   result.placement = rank <= 4 ? rank : null; result.knowdown_outcome = rank <= 4 ? 'placed' : 'eliminated';
  } else if (category.startsWith('topical')) {
   result.part1 = 30 + (index * 7 + number * 3) % 40;
   result.part2 = stage === 'scoring' && number % 2 === 0 ? null : 25 + (index * 11 + number * 5) % 45;
   result.score = result.part2 === null ? null : result.part1 + result.part2;
  } else result.score = category === 'project' ? 45 + index % 40 : 10 + index % 18;
  add('results', result);
 }
}
const output = process.argv[2];
if (!output) throw new Error('Usage: node scripts/generate-showcase.mjs OUTPUT.sql');
writeFileSync(output, sql.join('\n') + '\n');
console.log(`Generated ${output}: ${directory.schools.length} schools, 11 regions, no scorekeepers.`);
